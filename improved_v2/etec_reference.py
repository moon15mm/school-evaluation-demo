# ─────────────────────────────────────────────
# نموذج المؤشر — يحمل الشواهد التفصيلية
# ─────────────────────────────────────────────

@dataclass
class OfficialIndicator:
    code: str
    domain: str
    standard: str
    title: str
    keywords: list[str] = field(default_factory=list)
    evidence_required: list[str] = field(default_factory=list)
    # عدد الشواهد المطلوبة للوصول لكل مستوى
    level_thresholds: dict[str, int] = field(default_factory=lambda: {
        "متحقق مرتفعة جداً": 6,
        "متحقق مرتفعة": 4,
        "متحقق متوسطة": 2,
        "متحقق منخفضة": 0,
    })

    def __post_init__(self):
        if isinstance(self.evidence_required, str):
            self.evidence_required = [
                s.strip() for s in self.evidence_required.replace("،", ",").split(",") if s.strip()
            ]
        # تحديد حدود تلقائية بناءً على عدد الشواهد الفعلي
        n = len(self.evidence_required)
        if n > 0:
            self.level_thresholds = {
                "متحقق مرتفعة جداً": max(1, round(n * 0.7)),
                "متحقق مرتفعة":      max(1, round(n * 0.5)),
                "متحقق متوسطة":      max(1, round(n * 0.3)),
                "متحقق منخفضة":      0,
            }

    @property
    def evidence_count(self) -> int:
        return len(self.evidence_required)

    def score_from_achieved(self, achieved: int) -> float:
        """يحسب الدرجة المئوية بناءً على عدد الشواهد المتحققة."""
        if self.evidence_count == 0:
            return 0.0
        return round(min(achieved / self.evidence_count * 100, 100), 1)


