def get_indicators_for_level(level: str) -> list[OfficialIndicator]:
    if level in ("ابتدائي", "متوسط"):
        return INDICATORS_IBTIDAIY_MUTAWASIT
    return INDICATORS_THANAWI


def get_indicators_by_domain(domain: str, level: str = DEFAULT_LEVEL) -> list[OfficialIndicator]:
    return [ind for ind in get_indicators_for_level(level) if ind.domain == domain]


def get_indicator_by_code(code: str, level: str = DEFAULT_LEVEL) -> OfficialIndicator | None:
    return next((ind for ind in get_indicators_for_level(level) if ind.code == code), None)


def match_indicator(text: str, level: str = DEFAULT_LEVEL) -> list[tuple[OfficialIndicator, int]]:
    normalized = text.lower()
    results = []
    for indicator in get_indicators_for_level(level):
        hits = sum(1 for kw in indicator.keywords if kw in normalized)
        if indicator.code.lower() in normalized:
            hits += 5
        if hits > 0:
            results.append((indicator, hits))
    return sorted(results, key=lambda x: x[1], reverse=True)


def classify_school(score: float) -> str:
    for level, data in CLASSIFICATION_LEVELS.items():
        if score >= data["min_score"]:
            return level
    return "التهيئة"


def domain_label(domain_key: str) -> str:
    return OFFICIAL_DOMAINS.get(domain_key, domain_key)


def level_indicator_count(level: str) -> int:
    return len(get_indicators_for_level(level))


def get_evidence_summary(indicator: OfficialIndicator, achieved_count: int) -> str:
    """يعطي تقييماً نصياً بناءً على عدد الشواهد المتحققة."""
    total = indicator.evidence_count
    if total == 0:
        return "لا توجد شواهد محددة"
    pct = achieved_count / total * 100
    if pct >= 76:
        return f"متحقق مرتفعة جداً ({achieved_count}/{total} شاهد)"
    if pct >= 51:
        return f"متحقق مرتفعة ({achieved_count}/{total} شاهد)"
    if pct >= 26:
        return f"متحقق متوسطة ({achieved_count}/{total} شاهد)"
    return f"متحقق منخفضة ({achieved_count}/{total} شاهد)"


